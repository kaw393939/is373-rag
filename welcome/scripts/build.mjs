import { readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { compile } from 'svelte/compiler';
import { render } from 'svelte/server';
const source = await readFile('src/Welcome.svelte', 'utf8');
const compiled = compile(source, { filename: 'Welcome.svelte', generate: 'server', css: 'external' });
const warnings = compiled.warnings.filter(w => !w.code.startsWith('css_unused_selector'));
if (warnings.length) throw new Error(warnings.map(w => `${w.code}: ${w.message}`).join('\n'));
await rm('build', { recursive: true, force: true });
await mkdir('build');
await mkdir('.build', { recursive: true });
await writeFile('.build/Welcome.mjs', compiled.js.code);
const component = (await import(pathToFileURL(resolve('.build/Welcome.mjs')).href)).default;
const output = render(component);
await writeFile('build/welcome.css', compiled.css?.code ?? '');
await writeFile('build/index.html', `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">${output.head}<link rel="stylesheet" href="/welcome.css"></head><body>${output.body}</body></html>\n`);
await writeFile('build/robots.txt', 'User-agent: *\nDisallow: /\n');
console.log('Built static Svelte welcome screen; no client hydration or application backend.');
